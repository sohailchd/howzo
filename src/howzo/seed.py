def current_platform():
    """The platform howzo is running on: 'macos', 'linux', or 'windows'."""
    return config.platform_name()


_BY_NAME = {e[0]: e for e in SEED}


def entry(name):
    """The SEED tuple (name, platform, oneliner, when_to_use) for name."""
    return _BY_NAME.get(name)


def apply_seed(c, platform=None):
    """Merge SEED into the inventory; never clobber a local row's own text.

    A name that exists locally (source != 'seed') is left alone: the seed
    only fills an empty when_to_use / empty oneliner, and only when the entry
    is native to the running platform or marked 'all'. A local row that still
    carries a platform tag (it was seeded before the tool got installed) is
    cleared — a scanned row is native. Missing names are inserted as
    source='seed' with their platform recorded; their text is curated, so
    rescan re-syncs it from the bundled data (there is no user-facing editor
    for seed rows). Local rows' own text is never touched.

    Returns the number of rows written (inserted + filled).
    """
    plat = platform or current_platform()
    written = 0
    for name, entry_platform, oneliner, when_to_use in SEED:
        row = c.execute("SELECT source, oneliner, when_to_use, platform FROM tools WHERE name=?",
                        (name,)).fetchone()
        if row is not None and row["source"] != "seed":
            # a local row must never carry a seed's foreign tag, even if it
            # became installed after an earlier scan seeded it (self-heal)
            if row["platform"]:
                written += c.execute("UPDATE tools SET platform=NULL WHERE name=?",
                                     (name,)).rowcount
            if entry_platform in (ALL, plat):
                if not (row["when_to_use"] or ""):
                    written += c.execute(
                        "UPDATE tools SET when_to_use=? WHERE name=? AND when_to_use=''",
                        (when_to_use, name)).rowcount
                if not (row["oneliner"] or ""):
                    written += c.execute(
                        "UPDATE tools SET oneliner=? WHERE name=? AND oneliner=''",
                        (oneliner, name)).rowcount
            continue
        if row is None:
            c.execute("INSERT INTO tools(name, source, version, path, oneliner, when_to_use, platform) "
                      "VALUES(?,?,?,?,?,?,?)",
                      (name, "seed", "", "", oneliner, when_to_use, entry_platform))
            written += 1
        elif (row["oneliner"], row["when_to_use"], row["platform"]) != \
                (oneliner, when_to_use, entry_platform):
            # re-sync curated text on version bumps; skip no-ops so the
            # return value counts real writes
            c.execute("UPDATE tools SET oneliner=?, when_to_use=?, platform=? WHERE name=?",
                      (oneliner, when_to_use, entry_platform, name))
            written += 1
    return written
