"""Bundled knowledge base of the top macOS / Linux / Windows commands.

howzo can only rank words that appear in indexed text. A tool whose man page
never uses the words users type is invisible: `cat`'s man page says
"concatenate files", so "content of the file" had no way to reach it. SEED
closes that gap with curated entries for the commands people reach for most,
merged into the inventory at scan time (see apply_seed).

Each entry is (name, platform, oneliner, when_to_use):
  name       the command as typed (Windows cmd / PowerShell names included)
  platform   "all" | "macos" | "linux" | "windows" — where the command is at
             home. Entries of every platform are indexed so a macOS user can
             still find `ipconfig`; foreign rows carry a ranking penalty
             (match.rank_rows) so the machine's own tools win.
  oneliner   one terse, factual, man-page-style sentence
  when_to_use 4-12 words of the phrasing users actually type. Intent-specific
             on purpose: stuffing generic words ("file", "text") into many
             entries creates ranking collisions.

Seed rows only fill gaps: a name that exists locally is never replaced, and a
row's own when_to_use/oneliner is only filled when it is empty — a value you
set yourself always wins.
"""
